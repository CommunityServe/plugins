#!/usr/bin/env python3
"""Writes the generated half of src/mlx_serve/mlx/ffi.zig from the kit's mlx-c headers.

Usage: scripts/gen-mlx.py <kit dir>   (the kit's include/mlx/c/*.h; the plugin's file is rewritten in place)

Every mlx-c function becomes a declaration over the kit's `mlx_c`: an alias where it takes no pointer and no enum, else
a wrapper with Zig types that converts them (the exhaustive `mlx_dtype`, `mlx_device_type`, the optionals with
`some`/`none`, `char**` arguments, and pointers typed so an anonymous literal argument, `&.{ 1, 2 }`, takes its type). Functions with function-pointer parameters, and the names the
hand-written part above the marker defines, are left out. Nothing else is read or written.
"""
import pathlib
import re
import sys

BEGIN = "// ── generated by scripts/gen-mlx.py from the kit's mlx-c headers: do not edit below ──"

SCALARS = {
    "int": "c_int", "unsigned int": "c_uint", "size_t": "usize", "bool": "bool", "float": "f32", "double": "f64",
    "uint64_t": "u64", "int64_t": "i64", "uint32_t": "u32", "int32_t": "i32", "uint16_t": "u16", "int16_t": "i16",
    "uint8_t": "u8", "int8_t": "i8", "char": "u8",
}
ENUMS = {"mlx_dtype", "mlx_device_type"}
OPTIONALS = {"mlx_optional_int", "mlx_optional_float", "mlx_optional_dtype"}


def strip_comments(s):
    s = re.sub(r"/\*.*?\*/", " ", s, flags=re.S)
    return re.sub(r"//[^\n]*", " ", s)


def handles(text):
    return {m[1] for m in re.findall(r"typedef struct (mlx_\w+)_ \{[^}]*\} (mlx_\w+);", text, flags=re.S)}


def split_param(p):
    """'const mlx_array* res' -> ('const mlx_array*', 'res')."""
    p = " ".join(p.replace("*", " * ").split())
    m = re.match(r"^(.*?)\s*\b(\w+)$", p)
    if not m or m.group(1) in ("", "const", "struct"):
        return p.replace(" *", "*").replace("* ", "*"), None
    t = m.group(1).replace(" *", "*").replace("* ", "*").strip()
    return t, m.group(2)


def zig_name(n):
    if n in ("c", "std"):  # the file's own names
        return n + "_"
    return "@\"" + n + "\"" if n in ("type", "error", "fn", "var", "const", "align", "export", "test", "async",
                                     "struct", "enum", "union", "opaque", "and", "or", "inline", "noalias", "defer",
                                     "orelse", "catch", "try", "return", "break", "continue", "if", "else", "while",
                                     "for", "switch", "null", "undefined", "unreachable", "pub", "extern", "packed",
                                     "linksection", "comptime", "threadlocal", "usingnamespace", "anytype",
                                     "allowzero", "volatile", "resume", "suspend", "nosuspend", "await", "callconv",
                                     "errdefer", "asm", "noinline", "anyframe") else n


def param(ctype, name, hs):
    """(zig parameter type, the argument expression mlx-c is called with, needs_wrapper)."""
    t = ctype.replace("const ", "").strip()
    const = ctype.startswith("const ")
    stars = t.count("*")
    base = t.replace("*", "").strip()
    if stars == 0:
        if base in ENUMS:
            return base, f"@intCast(@intFromEnum({name}))", True
        if base in OPTIONALS:
            v = f"@intCast(@intFromEnum({name}.value))" if base == "mlx_optional_dtype" else f"{name}.value"
            return base, f".{{ .value = {v}, .has_value = {name}.has_value }}", True
        if base in hs:
            return base, name, False
        if base in SCALARS:
            return SCALARS[base], name, False
        if base.startswith("mlx_") and base.endswith(("_mode", "_norm")):
            return f"c.{base}", name, False
        return None
    if stars == 1:
        if base == "void":
            return ("?*const anyopaque" if const else "?*anyopaque"), name, False
        if base == "char":
            return "[*:0]const u8", name, False
        if base in ENUMS:
            return f"*{base}", f"@ptrCast({name})", True
        if base in hs or base in SCALARS:
            z = base if base in hs else SCALARS[base]
            return (f"[*]const {z}" if const else f"*{z}"), name, True
        return None
    if stars == 2:
        if base == "char":
            # An input list (`const char** data` with its size) or an out-parameter: whichever pointer the copy holds.
            return "anytype", f"@ptrCast(@constCast({name}))", True
        if base == "void":
            return "*?*anyopaque", name, False
        return None
    return None


def generate(headers, own):
    text = "\n".join(strip_comments(h.read_text()) for h in sorted(headers))
    hs = handles(text)
    body = re.sub(r"^\s*#.*$", " ", text, flags=re.M).replace('extern "C" {', " ")
    body = re.sub(r"^\s*\}\s*$", " ", body, flags=re.M)  # the `extern "C"` block's close
    decls = []
    for chunk in body.split(";"):
        if "{" in chunk or "}" in chunk or "typedef" in chunk:
            continue
        m = re.match(r"^\s*(.*?)\b(_?mlx_\w+)\s*\((.*)\)\s*$", chunk, flags=re.S)
        if not m:
            continue
        ret, name, params = " ".join(m.group(1).split()), m.group(2), " ".join(m.group(3).split())
        decls.append((name, None if ("(" in params or not ret) else (ret, params)))
    out, skipped, seen = [BEGIN, ""], [], set()
    for h in sorted(hs - own):
        out.append(f"pub const {h} = c.{h};")
    for name, sig in decls:
        if name in seen or name in own:
            continue
        seen.add(name)
        if sig is None:
            skipped.append(name)
            continue
        ret, params = sig
        ps = [] if params.strip() in ("", "void") else [p.strip() for p in params.split(",")]
        if any(p == "..." for p in ps) or re.search(r"\b(bfloat16_t|float16_t|mlx_complex64_t)\b", ret + " " + params):
            skipped.append(name)
            continue
        zs, args, wrap = [], [], False
        ok = True
        for i, p in enumerate(ps):
            ctype, pname = split_param(p)
            pname = zig_name(pname or f"a{i}")
            r = param(ctype, pname, hs)
            if r is None:
                ok = False
                break
            zs.append(f"{pname}: {r[0]}")
            args.append(r[1])
            wrap = wrap or r[2]
        rt = ret.replace("const ", "").strip()
        if not ok or (rt not in ("void",) and rt not in SCALARS and rt not in ENUMS and rt not in hs and "*" not in rt):
            skipped.append(name)
            continue
        if rt in ENUMS:
            wrap = True
        data = name.startswith("mlx_array_data_") and rt.endswith("*") and rt.rstrip("* ") in SCALARS
        if data:
            wrap = True
        if not wrap:
            out.append(f"pub const {name} = c.{name};")
            continue
        call = f"c.{name}({', '.join(args)})"
        if data:
            # the array's elements, null before it is evaluated
            zr, body = f"?[*]const {SCALARS[rt.rstrip('* ')]}", f"return {call};"
        elif rt in ENUMS:
            zr, body = rt, f"return @enumFromInt({call});"
        elif rt == "void":
            zr, body = "void", f"{call};"
        elif rt in SCALARS:
            zr, body = SCALARS[rt], f"return {call};"
        elif rt in hs:
            zr, body = rt, f"return {call};"
        else:
            zr, body = f"@typeInfo(@TypeOf(c.{name})).@\"fn\".return_type.?", f"return {call};"
        out.append(f"pub fn {name}({', '.join(zs)}) {zr} {{\n    {body}\n}}")
    out.append("")
    out.append("// Left to the hand-written part (function-pointer or untranslated parameters): " + ", ".join(sorted(skipped)) + ".")
    out.append("")
    return "\n".join(out)


def main():
    kit = pathlib.Path(sys.argv[1])
    headers = list((kit / "include/mlx/c").glob("*.h"))
    if not headers:
        sys.exit(f"no mlx-c headers under {kit}/include/mlx/c")
    ffi = pathlib.Path(__file__).resolve().parent.parent / "src/mlx_serve/mlx/ffi.zig"
    cur = ffi.read_text()
    at = cur.find(BEGIN)
    if at < 0:
        sys.exit(f"{ffi}: no generated section marker")
    own = set(re.findall(r"^pub (?:const|fn|var) (\w+)", cur[:at], flags=re.M))
    ffi.write_text(cur[:at] + generate(headers, own))
    print(f"wrote the generated section of {ffi}")


if __name__ == "__main__":
    main()
